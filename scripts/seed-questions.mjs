#!/usr/bin/env node
// MedDuel — generate supabase/seed.sql from the legacy data files.
//
// Reads:
//   src/data/questions.js          → QUESTIONS array
//   src/data/cases.js              → DOSSIER_CASES array
//   src/data/detective_cases.js    → detective cases (auto-detected variable)
//
// Writes:
//   supabase/seed.sql              (re-applied automatically by `supabase db reset`)
//
// Usage:
//   node scripts/seed-questions.mjs
//
// The script is intentionally dependency-free so it runs on a clean
// `npm install` without anything else. It eval()s the data files in a
// vm.Sandbox where window/document/etc. are stubbed.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root      = resolve(__dirname, '..');

// ── helpers ──────────────────────────────────────────────────────────────
const sqlString = s =>
  s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;

const sqlJson = obj =>
  obj == null ? 'null' : `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;

const sqlBool = b => (b ? 'true' : 'false');

const sqlNum  = n => (n == null || Number.isNaN(+n) ? 'null' : String(+n));

const sqlArr = (arr) =>
  arr == null
    ? 'null'
    : `array[${arr.map(s => sqlString(s)).join(',')}]::text[]`;

function loadDataFile(relPath, expectedGlobal) {
  // The legacy data files use top-level `const QUESTIONS = [...]`. In a
  // vm.Context, top-level const/let are NOT exposed on the sandbox object.
  // Rewrite top-level `const`/`let` declarations of array names into
  // `globalThis.X = [...]` so they become sandbox globals after eval.
  let src = readFileSync(resolve(root, relPath), 'utf8');
  src = src.replace(
    /^(?:const|let|var)\s+([A-Z_][A-Z0-9_]*)\s*=/gm,
    'globalThis.$1 ='
  );

  const sandbox = { window: {}, document: {}, console, globalThis: {} };
  sandbox.globalThis = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(src, sandbox, { filename: relPath });

  if (expectedGlobal) {
    if (!Array.isArray(sandbox[expectedGlobal])) {
      throw new Error(`${relPath} did not define ${expectedGlobal}`);
    }
    return sandbox[expectedGlobal];
  }
  // detective_cases.js: pick the largest array we found.
  let best = null;
  for (const v of Object.values(sandbox)) {
    if (Array.isArray(v) && (!best || v.length > best.length)) best = v;
  }
  return best || [];
}

// ── load ─────────────────────────────────────────────────────────────────
console.log('Reading data files…');
const QUESTIONS  = loadDataFile('src/data/questions.js',        'QUESTIONS');
const DOSSIER    = loadDataFile('src/data/cases.js',            'DOSSIER_CASES');
const DETECTIVE  = loadDataFile('src/data/detective_cases.js',  null);
console.log(`  ${QUESTIONS.length} questions, ${DOSSIER.length} dossier cases, ${DETECTIVE.length} detective cases`);

// ── build seed.sql ───────────────────────────────────────────────────────
const lines = [];
lines.push('-- MedDuel — generated by scripts/seed-questions.mjs');
lines.push(`-- Generated at ${new Date().toISOString()}`);
lines.push('-- DO NOT EDIT BY HAND — re-run the script to regenerate.');
lines.push('');
lines.push('begin;');
lines.push('');
lines.push('truncate public.questions             cascade;');
lines.push('truncate public.dossier_cases         cascade;');
lines.push('truncate public.detective_cases       cascade;');
lines.push('');

// ── questions ────────────────────────────────────────────────────────────
lines.push('-- ── questions ──');
QUESTIONS.forEach((q, idx) => {
  // Map legacy `c` (number for diagnose, boolean for truefalse) to jsonb.
  const correctJson = sqlJson(q.c);
  lines.push(`insert into public.questions (
  legacy_idx, type, domain, display_label, question_text,
  options, correct, explanation, wiki, fig, difficulty, subtype, status,
  source_locale
) values (
  ${idx},
  ${sqlString(q.type || 'diagnose')}::question_type,
  ${sqlString(q.domain || 'lab')},
  ${sqlString(q.dl || '')},
  ${sqlString(q.q || '')},
  ${q.a ? sqlJson(q.a) : 'null'},
  ${correctJson},
  ${sqlString(q.ex || '')},
  ${q.wiki ? sqlJson(q.wiki) : 'null'},
  ${q.fig  ? sqlJson(q.fig)  : 'null'},
  ${sqlNum(q.d || 3)},
  ${sqlString(q.subtype || null)},
  'published',
  'nl'
);`);
});
lines.push('');

// ── dossier_cases ────────────────────────────────────────────────────────
lines.push('-- ── dossier_cases ──');
DOSSIER.forEach((c) => {
  lines.push(`insert into public.dossier_cases (
  id, patient, diagnosis, clues, options, correct, explanation,
  status, source_locale
) values (
  ${sqlString(c.id)},
  ${sqlString(c.patient || '')},
  ${sqlString(c.diagnosis || '')},
  ${sqlJson(c.clues || [])},
  ${sqlJson(c.options || [])},
  ${sqlNum(c.correct ?? 0)},
  ${sqlString(c.explanation || '')},
  'published',
  'nl'
);`);
});
lines.push('');

// ── detective_cases ──────────────────────────────────────────────────────
lines.push('-- ── detective_cases ──');
DETECTIVE.forEach((c, idx) => {
  const id = c.id || `dc${idx + 1}`;
  lines.push(`insert into public.detective_cases (
  id, payload, status, source_locale
) values (
  ${sqlString(id)},
  ${sqlJson(c)},
  'published',
  'nl'
);`);
});
lines.push('');

lines.push('commit;');
lines.push('');

// ── write ────────────────────────────────────────────────────────────────
const outDir = resolve(root, 'supabase');
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'seed.sql');
writeFileSync(outFile, lines.join('\n'), 'utf8');

const sizeKB = (Buffer.byteLength(lines.join('\n'), 'utf8') / 1024).toFixed(1);
console.log(`Wrote ${outFile}  (${sizeKB} KB, ${lines.length} lines)`);
console.log('Apply locally with:  npm run supabase:reset');
